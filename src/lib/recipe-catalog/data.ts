type Ing = [Localized<string>, number, string, Localized<string>?];

function recipe(
  id: string,
  name: [string, string],
  servings: number,
  tags: RecipeTag[],
  ingredients: Ing[],
  steps: [string[], string[]],
): CatalogRecipe {
  return {
    id,
    name: w(name[0], name[1]),
    servings,
    ingredients: ingredients.map(
      ([n, quantity, unit, note]): CatalogIngredient => ({
        name: n,
        quantity,
        unit,
        ...(note ? { note } : {}),
      }),
    ),
    instructions: w(steps[0].join("\n"), steps[1].join("\n")),
    tags,
  };
}

